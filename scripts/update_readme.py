#!/usr/bin/env python3
"""Rebuild the progress table in README.md and the review list in REVIEW.md from problem front matter.

Only problems with `status: Solved` are listed. Problems with `review: true` also go in REVIEW.md.
"""
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
REVIEW = ROOT / "REVIEW.md"
START, END = "<!-- PROBLEMS:START -->", "<!-- PROBLEMS:END -->"


def parse(path):
    match = re.match(r"---\n(.*?)\n---", path.read_text(), re.S)
    if not match:
        return None
    meta = dict(
        line.split(":", 1) for line in match.group(1).splitlines() if ":" in line
    )
    return {k.strip(): v.strip() for k, v in meta.items()}


def main():
    problems = []
    for readme in (ROOT / "problems").glob("*/*.md"):
        meta = parse(readme)
        if meta and meta.get("status") == "Solved":
            meta["folder"] = readme.parent.name
            problems.append(meta)
    problems.sort(key=lambda m: int(m["number"]))

    difficulty = Counter(m["difficulty"] for m in problems)
    topics = Counter(t.strip() for m in problems for t in m["topics"].split(","))

    rows = [
        f"| {m['number']} | [{m['title']}](problems/{m['folder']}/{m['slug']}.md) "
        f"| {m['difficulty']} | {m['topics']} "
        f"| [C++](problems/{m['folder']}/{m['slug']}.cpp) | {m['date']} |"
        for m in problems
    ]
    topic_line = " · ".join(f"{t} ({n})" for t, n in topics.most_common())

    parts = [
        "| Solved | Easy | Medium | Hard |",
        "|:------:|:----:|:------:|:----:|",
        f"| **{len(problems)}** | {difficulty['Easy']} | {difficulty['Medium']} | {difficulty['Hard']} |",
        "",
    ]
    if topic_line:
        parts += [f"**Topics:** {topic_line}", ""]
    parts += [
        "| # | Problem | Difficulty | Topics | Solution | Solved |",
        "|--:|---------|------------|--------|----------|--------|",
        *rows,
    ]

    block = f"{START}\n" + "\n".join(parts) + f"\n{END}"
    text = re.sub(f"{START}.*?{END}", lambda _: block, README.read_text(), flags=re.S)
    README.write_text(text)

    flagged = [m for m in problems if m.get("review") == "true"]
    write_review(flagged)
    print(f"Updated README with {len(problems)} problems, REVIEW.md with {len(flagged)}")


def write_review(flagged):
    lines = [
        "# Problems to Revisit",
        "",
        "Problems I solved but struggled with, to re-solve from scratch later. "
        "Generated by `scripts/update_readme.py` from `review: true` in each write-up.",
        "",
    ]
    if not flagged:
        lines.append("Nothing flagged right now.")
    else:
        lines += [
            "| # | Problem | Difficulty | Topics | Solved | What tripped me up |",
            "|--:|---------|------------|--------|--------|--------------------|",
        ]
        for m in flagged:
            reason = m.get("review_reason", "").replace("|", "\\|")
            lines.append(
                f"| {m['number']} | [{m['title']}](problems/{m['folder']}/{m['slug']}.md) "
                f"([LeetCode](https://leetcode.com/problems/{m['slug']}/)) "
                f"| {m['difficulty']} | {m['topics']} | {m['date']} "
                f"| {reason} |"
            )
    REVIEW.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
